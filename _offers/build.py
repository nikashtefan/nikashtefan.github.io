def corners(a, b, c):
    return f'<div class="corners"><span class="mark">{a}</span><span class="mid mark">{b}</span><span class="mark right">{c}</span></div>'


def cards(items):
    return '<div class="cards reveal">' + "".join(
        f'<div class="card"><h3>{h}</h3><p>{p}</p><span class="term">{t}</span></div>' for h, p, t in items
    ) + "</div>"


